// Provenance + coverage report: which sources fed which questions, how much was enhanced or new, and which
// source pages are referenced. Output: reports/content-report.json and reports/CONTENT_REPORT.md (aliases only).
import fs from 'node:fs';
import path from 'node:path';

const ROOT = path.resolve(import.meta.dirname, '../..');
const read = (p) => JSON.parse(fs.readFileSync(path.join(ROOT, p), 'utf8'));
const cats = read('content/categories.json');
const extraction = fs.existsSync(path.join(ROOT, 'reports/extraction.json')) ? read('reports/extraction.json') : [];
const pagesBySource = new Map(extraction.map((e) => [e.source, e]));

const bySource = new Map();
const byCat = new Map(cats.map((c) => [c.id, { category: c.id, total: 0, 'reference-derived': 0, enhanced: 0, new: 0, diagrams: 0, detailedWords: 0 }]));
let total = 0;
for (const f of fs.readdirSync(path.join(ROOT, 'content/questions')).filter((x) => x.endsWith('.json')).sort()) {
  const doc = read('content/questions/' + f);
  for (const q of doc.questions) {
    total++;
    const c = byCat.get(doc.category);
    c.total++;
    c[q.sourceType]++;
    c.diagrams += q.diagrams?.length || 0;
    c.detailedWords += q.detailed.trim().split(/\s+/).length;
    for (const s of q.sources || []) {
      const e = bySource.get(s.file) || bySource.set(s.file, { source: s.file, questions: 0, pages: new Set() }).get(s.file);
      e.questions++;
      const pg = s.pages || [];
      if (pg.length === 2 && pg[1] >= pg[0]) for (let p = pg[0]; p <= pg[1]; p++) e.pages.add(p);
      else pg.forEach((p) => e.pages.add(p));
    }
  }
}
const sources = [...bySource.values()].map((e) => {
  const meta = pagesBySource.get(e.source);
  const referenced = [...e.pages].filter((p) => !meta || p <= meta.pages).length;
  return { source: e.source, totalPages: meta?.pages ?? null, pagesReferenced: referenced, coveragePct: meta ? Math.round((referenced / meta.pages) * 100) : null, questionsCiting: e.questions };
}).sort((a, b) => a.source.localeCompare(b.source));
const unreferenced = extraction.filter((e) => !bySource.has(e.source)).map((e) => e.source);
const totals = [...byCat.values()].reduce((t, c) => ({ derived: t.derived + c['reference-derived'], enhanced: t.enhanced + c.enhanced, new: t.new + c.new }), { derived: 0, enhanced: 0, new: 0 });
const report = {
  generatedFrom: 'content/questions/*.json and reports/extraction.json',
  note: 'Page coverage is approximate: it is the union of page ranges cited in each question\'s sources. Source names are neutral aliases; real file names stay in git-ignored folders.',
  totalQuestions: total,
  totals,
  categories: [...byCat.values()],
  sources,
  extractedButUncited: unreferenced,
};
fs.writeFileSync(path.join(ROOT, 'reports/content-report.json'), JSON.stringify(report, null, 2));
const md = `# Content provenance report

Generated by \`npm run report\`. ${total} questions. Reference-derived: ${totals.derived}, enhanced: ${totals.enhanced}, new: ${totals.new}.

## By topic

| Topic | Questions | Reference-derived | Enhanced | New | Diagrams | Detailed words |
|---|---:|---:|---:|---:|---:|---:|
${report.categories.map((c) => `| ${c.category} | ${c.total} | ${c['reference-derived']} | ${c.enhanced} | ${c.new} | ${c.diagrams} | ${c.detailedWords} |`).join('\n')}

## Source coverage (approximate)

| Source (alias) | Pages | Pages cited | Coverage | Questions citing |
|---|---:|---:|---:|---:|
${sources.map((s) => `| ${s.source} | ${s.totalPages ?? '?'} | ${s.pagesReferenced} | ${s.coveragePct ?? '?'}% | ${s.questionsCiting} |`).join('\n')}
${unreferenced.length ? `\nExtracted but not cited by any question: ${unreferenced.join(', ')}.\n` : ''}
${note()}
`;
function note() {
  return '\nCoverage is computed from the page ranges authors recorded. Authors often cite broad ranges, so it overstates how much of each source was used; it shows where the notes were consulted, not that every sentence was reviewed. The role/technology map (ref-jd-technology-map) was used only to order the learning paths and is deliberately not cited in questions. Sections of the notes that were personal positioning, answer-style meta text or exact interview-specific wording were intentionally not carried over.';
}
fs.writeFileSync(path.join(ROOT, 'reports/CONTENT_REPORT.md'), md);
console.log(`content report: ${total} questions (${totals.derived} reference-derived, ${totals.enhanced} enhanced, ${totals.new} new); ${sources.length} sources cited`);
